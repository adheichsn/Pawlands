local PetInventoryService = require(script.Parent.Pets.PetInventoryService)
local PetInventoryRemoteService = require(script.Parent.Pets.PetInventoryRemoteService)
local PetPartyService = require(script.Parent.Pets.PetPartyService)
local PetCombatService = require(script.Parent.Pets.PetCombatService)
local PetCombatFeedbackService = require(script.Parent.Pets.PetCombatFeedbackService)
local PetVitalsService = require(script.Parent.Pets.PetVitalsService)
local StudioPetPreview = require(script.Parent.Pets.StudioPetPreview)
local SlimeMovementService = require(script.Parent.Slimes.SlimeMovementService)
local CombatService = require(script.Parent.Combat.CombatService)
local DialogueService = require(script.Parent.Dialogue.DialogueService)
local TutorialService = require(script.Parent.Tutorial.TutorialService)
local StarterPetService = require(script.Parent.Tutorial.StarterPetService)

PetInventoryService.Start()
PetPartyService.Start(PetInventoryService)
PetVitalsService.Start(PetInventoryService, PetPartyService)
PetCombatService.Start(PetPartyService, PetVitalsService, PetInventoryService)
PetCombatFeedbackService.Start()
StudioPetPreview.Start(PetPartyService, PetInventoryService, PetVitalsService, PetCombatFeedbackService)
SlimeMovementService.Start(PetCombatService, PetVitalsService, PetCombatFeedbackService)
CombatService.Start()
TutorialService.Start(SlimeMovementService)
StarterPetService.Start(PetInventoryService, TutorialService)
PetInventoryRemoteService.Start(PetInventoryService, PetPartyService, TutorialService)
DialogueService.Start(TutorialService.HandleDialogueAction)
print("[Pawlands] Pet, combat, movement, dialogue, and tutorial foundations ready.")

script.Destroying:Connect(function()
	DialogueService.Stop()
	PetInventoryRemoteService.Stop()
	StarterPetService.Stop()
	TutorialService.Stop()
	CombatService.Stop()
	SlimeMovementService.Stop()
	PetCombatFeedbackService.Stop()
	PetCombatService.Stop()
	PetVitalsService.Stop()
end)
