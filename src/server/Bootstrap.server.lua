local PlayerProfileService = require(script.Parent.Profile.PlayerProfileService)
local ProfileDevCommands = require(script.Parent.Profile.ProfileDevCommands)
local EconomyService = require(script.Parent.Economy.EconomyService)
local PetInventoryService = require(script.Parent.Pets.PetInventoryService)
local PetProgressionService = require(script.Parent.Progression.PetProgressionService)
local HandlerProgressionService = require(script.Parent.Progression.HandlerProgressionService)
local PartyPowerService = require(script.Parent.Progression.PartyPowerService)
local CombatContributionService = require(script.Parent.Combat.CombatContributionService)
local PetInventoryRemoteService = require(script.Parent.Pets.PetInventoryRemoteService)
local PetPartyService = require(script.Parent.Pets.PetPartyService)
local PetPartyMutationGuard = require(script.Parent.Pets.PetPartyMutationGuard)
local PetCombatService = require(script.Parent.Pets.PetCombatService)
local PetCombatFeedbackService = require(script.Parent.Pets.PetCombatFeedbackService)
local PetVitalsService = require(script.Parent.Pets.PetVitalsService)
local StudioPetPreview = require(script.Parent.Pets.StudioPetPreview)
local SlimeMovementService = require(script.Parent.Slimes.SlimeMovementService)
local WorldSlimeService = require(script.Parent.Slimes.WorldSlimeService)
local CombatService = require(script.Parent.Combat.CombatService)
local DialogueService = require(script.Parent.Dialogue.DialogueService)
local TutorialService = require(script.Parent.Tutorial.TutorialService)
local StarterPetService = require(script.Parent.Tutorial.StarterPetService)

PlayerProfileService.Start()
EconomyService.Start(PlayerProfileService)
ProfileDevCommands.Start(PlayerProfileService)
PetInventoryService.Start(PlayerProfileService)
PetProgressionService.Start(PetInventoryService)
HandlerProgressionService.Start(PlayerProfileService)
CombatContributionService.Start()
PetPartyService.Start(PetInventoryService, PlayerProfileService)
PartyPowerService.Start(PetPartyService, PetInventoryService)
PetVitalsService.Start(PetInventoryService, PetPartyService, PetProgressionService)
PetCombatService.Start(PetPartyService, PetVitalsService, PetInventoryService, PetProgressionService, CombatContributionService)
PetCombatFeedbackService.Start()
StudioPetPreview.Start(PetPartyService, PetInventoryService, PetVitalsService, PetCombatFeedbackService)
SlimeMovementService.Start(PetCombatService, PetVitalsService, PetCombatFeedbackService)
WorldSlimeService.Start(PetCombatService, PetVitalsService, PetCombatFeedbackService)
PetPartyMutationGuard.Start()
CombatService.Start(HandlerProgressionService, CombatContributionService)
TutorialService.Start(SlimeMovementService, PetPartyService, PlayerProfileService)
StarterPetService.Start(PetInventoryService, TutorialService, PlayerProfileService)
PetInventoryRemoteService.Start(PetInventoryService, PetPartyService, TutorialService, PetPartyMutationGuard)
DialogueService.Start(TutorialService.HandleDialogueAction)
print("[Pawlands] Profile, Pet, progression, combat, movement, dialogue, and tutorial foundations ready.")

script.Destroying:Connect(function()
	DialogueService.Stop()
	PetInventoryRemoteService.Stop()
	StarterPetService.Stop()
	TutorialService.Stop()
	CombatService.Stop()
	PetPartyMutationGuard.Stop()
	PartyPowerService.Stop()
	WorldSlimeService.Stop()
	SlimeMovementService.Stop()
	PetCombatFeedbackService.Stop()
	PetCombatService.Stop()
	CombatContributionService.Stop()
	PetVitalsService.Stop()
	HandlerProgressionService.Stop()
	PetProgressionService.Stop()
	ProfileDevCommands.Stop()
	EconomyService.Stop()
	PlayerProfileService.Stop()
end)
