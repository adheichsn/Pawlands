local PetInventoryService = require(script.Parent.Pets.PetInventoryService)
local PetPartyService = require(script.Parent.Pets.PetPartyService)
local PetCombatService = require(script.Parent.Pets.PetCombatService)
local PetVitalsService = require(script.Parent.Pets.PetVitalsService)
local StudioPetPreview = require(script.Parent.Pets.StudioPetPreview)
local SlimeMovementService = require(script.Parent.Slimes.SlimeMovementService)
local CombatService = require(script.Parent.Combat.CombatService)

PetInventoryService.Start()
PetPartyService.Start(PetInventoryService)
PetVitalsService.Start(PetInventoryService, PetPartyService)
PetCombatService.Start(PetPartyService, PetVitalsService)
StudioPetPreview.Start(PetPartyService, PetInventoryService, PetVitalsService)
SlimeMovementService.Start(PetCombatService, PetVitalsService)
CombatService.Start()
print("[Pawlands] Pet vitals, pet combat, movement, slime AI, and player combat foundations ready.")

script.Destroying:Connect(function()
	CombatService.Stop()
	SlimeMovementService.Stop()
	PetCombatService.Stop()
	PetVitalsService.Stop()
end)
